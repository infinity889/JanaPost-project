export const DEMO_RAW_INPUT_DATASET: RawAddressItem[] = DEMO_PARSED_DATASET.map((item) => ({
  id: item.id,
  raw_address: item.raw_address,
}));

export function generateLargeBatchDataset(totalCount = 1000): AddressRecordUI[] {
  const results: AddressRecordUI[] = [];
  for (let i = 0; i < totalCount; i++) {
    const base = DEMO_PARSED_DATASET[i % DEMO_PARSED_DATASET.length];
    const seqNum = String(i + 1).padStart(5, '0');
    if (i < DEMO_PARSED_DATASET.length) {
      results.push({ ...base });
    } else {
      const houseVariant = base.house ? `${base.house}` : `${(i % 140) + 1}`;
      results.push({
        ...base,
        id: `rec_${seqNum}`,
        house: houseVariant,
      });
    }
  }
  return results;
}
